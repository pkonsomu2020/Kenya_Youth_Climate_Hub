#!/usr/bin/env bash
# ============================================================
# Deploy KYCH on the shared Contabo VPS (/var/www/kych, PM2 app "kych", port 3028).
# Touches ONLY this app: never restarts other PM2 processes on the server.
#
#   cd /var/www/kych && bash scripts/deploy-contabo.sh
#
# Needs write access to /var/www/kych for the user running it. If files are
# owned by someone else, fix ownership first (asks for the sudo password):
#   sudo chown -R "$(whoami):$(whoami)" /var/www/kych
# ============================================================
set -euo pipefail

APP=kych
PORT=3028
cd "$(dirname "$0")/.."

echo "==> Checking write access"
if [ ! -w .git ] || [ ! -w . ]; then
  echo "No write access to $(pwd). Run: sudo chown -R \"$(whoami):$(whoami)\" $(pwd)" >&2
  exit 1
fi

echo "==> Pulling main"
# package-lock.json drifts when a different npm version runs install; it is regenerated by npm ci.
git checkout -- package-lock.json 2>/dev/null || true
if ! git diff --quiet; then
  echo "Uncommitted server changes found; stop and review them first:" >&2
  git status --short >&2
  exit 1
fi
before=$(git rev-parse --short HEAD)
git pull --ff-only origin main
after=$(git rev-parse --short HEAD)
echo "    $before -> $after"

echo "==> Installing dependencies"
npm ci --no-audit --no-fund

echo "==> Building"
npm run build

echo "==> Reloading PM2 app '$APP' only"
pm2 reload "$APP" --update-env
pm2 save >/dev/null

echo "==> Health check"
for i in $(seq 1 20); do
  code=$(curl -s -o /dev/null -w "%{http_code}" "http://127.0.0.1:$PORT/" || true)
  [ "$code" = "200" ] && break
  sleep 2
done
echo "    http://127.0.0.1:$PORT/ -> $code"
[ "$code" = "200" ] || { echo "App did not come back healthy; check: pm2 logs $APP --lines 80" >&2; exit 1; }
echo "Deployed $after"
